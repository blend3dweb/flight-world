import {wgslFn} from './vendor/tsl.js';
export const hash2=wgslFn(`fn hash2(p:vec2f)->f32{var q=fract(vec3f(p.x,p.y,p.x)*.1031);q+=dot(q,q.yzx+33.33);return fract((q.x+q.y)*q.z);}`);
export const noise2=wgslFn(`fn noise2(p:vec2f)->f32{let i=floor(p);let f=fract(p);let u=f*f*(3.-2.*f);return mix(mix(hash2(i),hash2(i+vec2f(1.,0.)),u.x),mix(hash2(i+vec2f(0.,1.)),hash2(i+vec2f(1.,1.)),u.x),u.y);}`,[hash2]);
export const fbm=wgslFn(`fn fbm(p0:vec2f)->f32{var p=p0;var n=0.;var a=.52;for(var i=0;i<5;i++){n+=a*noise2(p);p=mat2x2f(.8,-.6,.6,.8)*p*2.07+vec2f(7.1,3.9);a*=.49;}return n;}`,[noise2]);
export const skyNight=wgslFn(`fn skyNight(base:vec3f,d:vec3f,sun:vec3f,moon:vec3f,day:f32,storm:f32,cover:f32,origin:vec2f)->vec3f{
 let night=1.-smoothstep(-.12,.13,sun.y);let twilight=exp(-abs(sun.y)*13.);
 let horizon=exp(-max(d.y,0.)*5.5);
 var daytime=mix(vec3f(.035,.16,.38),vec3f(.52,.68,.76),horizon);
 // Retain the analytic scattering colour without clipping the whole horizon to white.
 daytime=mix(daytime,clamp(base*.024,vec3f(0.),vec3f(1.35)),.34);
 var dark=mix(vec3f(.010,.020,.043),vec3f(.0012,.0025,.007),pow(max(d.y,0.),.42));
 let cellA=floor(d*1250.);let cellB=floor(d*3100.);
 let seedA=hash2(cellA.xy+cellA.z*.53);let seedB=hash2(cellB.yz+cellB.x*.37);
 let starA=step(.9995,seedA)*mix(.35,.75,hash2(cellA.xz));let starB=step(.99988,seedB)*.28;
 let starFade=smoothstep(.025,.20,d.y)*smoothstep(.08,.34,-sun.y)*(1.-storm*.92);
 dark+=mix(vec3f(.50,.66,1.),vec3f(1.,.72,.48),hash2(cellA.xy+19.))*((starA+starB)*starFade*.13);
 let md=max(dot(d,moon),0.);let moonDisk=smoothstep(.99978,.99988,md);let moonHalo=pow(md,260.)*.048;
 dark+=vec3f(.74,.84,1.)*(moonDisk*1.7+moonHalo)*(1.-storm*.75);
 var c=mix(daytime,dark,night);
 let facing=pow(max(dot(normalize(d.xz),normalize(sun.xz)),0.),4.);
 c+=(vec3f(.72,.13,.026)*facing+vec3f(.10,.018,.055))*twilight*horizon;
 c+=vec3f(3.,2.3,1.4)*smoothstep(.99993,.99996,dot(d,sun))*day*(1.-storm);
 c=mix(c,mix(vec3f(.009,.015,.025),vec3f(.25,.30,.34),day),storm*.67);
 let projection=d.xz/max(d.y,.032);
 let p=projection*.58+origin;
 let broad=fbm(p*.48+vec2f(4.7,-2.3));let billow=fbm(p+fbm(p*.38)*1.35);let detail=fbm(p*2.35+12.7);
 let cellular=billow+detail*.16+broad*.20;
 let raw=smoothstep(.76-cover*.36,.90-cover*.31,cellular);
 let wisps=smoothstep(.72,.88,fbm(projection*.22-origin*.18+31.))*smoothstep(.18,.65,d.y)*(1.-storm)*.22;
 let density=clamp(1.-exp(-raw*(2.0+storm*3.8))+wisps,0.,.96);
 let shade=clamp(.43+(billow-fbm(p+sun.xz*.45))*3.5+broad*.18,.05,1.);
 let sunset=(1.-smoothstep(.03,.30,abs(sun.y)))*(1.-night);
 let lit=mix(vec3f(1.10,1.14,1.12),vec3f(1.42,.57,.20),sunset*.86);
 var cloud=mix(vec3f(.16,.21,.27),lit,shade);
 cloud=mix(cloud,vec3f(.16,.20,.24)+shade*.20,storm*.80)*mix(.035,1.,day)+vec3f(.006,.010,.019)*(1.-day);
 let cloudHorizon=smoothstep(.006,.075,d.y)*(1.-smoothstep(.72,1.,d.y)*.16);
 c=mix(c,cloud,density*cloudHorizon);
 return max(c,vec3f(0.));
}`,[fbm,hash2]);
